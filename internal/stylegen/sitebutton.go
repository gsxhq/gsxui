// siteButtonPath is the site-only Button fallback stylesheet, slash-separated
// and relative to the repository root. It is a GENERATED artifact: every rule
// in it is Button's own recipe rule restated inside the site scope.
const siteButtonPath = "web/site-button.css"

// siteButtonComponent is the one component the fallback covers.
const siteButtonComponent = "button"

// siteButtonScope is the ancestor compound every rule in the fallback carries.
// It excludes the theme-preview body, which renders real <ui.Button>s under a
// different style and must not receive the default style's fallback.
const siteButtonScope = ":where(body:not([data-theme-button-preview]))"

// siteButtonHeader is the generated file's provenance comment.
const siteButtonHeader = `/* Code generated by cmd/stylegen from registry/styles/` + DefaultStyle + `/button.css. DO NOT EDIT.

   Site-only Nova fallback for the canonical tokenized Button used by docs and
   demos: raw markup that carries [data-gsxui-slot-button] without rendering
   through <ui.Button>. Consumer projects receive concrete inline utilities
   instead and never see this file.

   Every rule below is one of Button's recipe rules re-expressed against the
   slot marker inside the site scope, at zero specificity in @layer components
   so a real Button's own compiled utilities always beat it. */
`

// siteButtonRule is one emitted rule: a complex selector and the utilities the
// recipe applies in the state that selector encodes.
type siteButtonRule struct {
	selector  string
	utilities []string
}

// siteButtonVariant is how one Tailwind variant from Button's recipe is
// re-expressed as selector syntax. Exactly one field is set.
type siteButtonVariant struct {
	// attr is an attribute compound that qualifies the marker itself, e.g.
	// `[aria-invalid="true"]`.
	attr string
	// pseudo is a pseudo-class suffix on the subject, e.g. `:hover`.
	pseudo string
	// descendant is a descendant combinator plus compound, e.g. ` svg`.
	descendant string
	// dark selects the `.dark` ancestor arm.
	dark bool
}

// siteButtonVariants maps every Tailwind variant Button's recipe is allowed to
// use to its selector form. It is a CLOSED table on purpose: a recipe that
// starts using a variant nobody has translated fails generation loudly instead
// of silently emitting a fallback rule that targets the wrong elements.
//
// Quoting is normalized to double quotes here because the recipe writes
// `[class*='size-']` inside a Tailwind arbitrary variant, where a double quote
// would terminate the @apply argument.
var siteButtonVariants = map[string]siteButtonVariant{
	"dark":                {dark: true},
	"hover":               {pseudo: ":hover"},
	"focus-visible":       {pseudo: ":focus-visible"},
	"active":              {pseudo: ":active"},
	"disabled":            {pseudo: ":disabled"},
	"not-aria-[haspopup]": {pseudo: ":not([aria-haspopup])"},
	// Spelled without the space a CSS formatter would put inside the
	// parentheses: the layer gate's selector parser normalizes it away, and the
	// exemptions derived from these rules have to key on the selector the gate
	// reports, not on the one a formatter prefers.
	"has-[>svg]":                    {pseudo: ":has(>svg)"},
	"has-data-[icon=inline-start]":  {pseudo: `:has([data-icon="inline-start"])`},
	"has-data-[icon=inline-end]":    {pseudo: `:has([data-icon="inline-end"])`},
	"aria-invalid":                  {attr: `[aria-invalid="true"]`},
	"aria-expanded":                 {attr: `[aria-expanded="true"]`},
	"[&_svg]":                       {descendant: " svg"},
	`[&_svg:not([class*='size-'])]`: {descendant: ` svg:not([class*="size-"])`},
}

// siteButtonStylesheet renders Button's recipe as the site fallback. It returns
// both the file bytes and the structured rules, because the layer gate derives
// its exemptions from the same rules rather than from a hand-copied list.
func siteButtonStylesheet(shape recipe.Shape, style recipe.Style) ([]byte, []siteButtonRule, error) {
	rules, err := siteButtonRules(shape, style)
	if err != nil {
		return nil, nil, err
	}
	var b strings.Builder
	b.WriteString(siteButtonHeader)
	b.WriteString("@layer components {\n")
	for _, rule := range rules {
		fmt.Fprintf(&b, "  %s {\n    @apply %s;\n  }\n", rule.selector, strings.Join(rule.utilities, " "))
	}
	b.WriteString("}\n")
	return []byte(b.String()), rules, nil
}

// siteButtonRules re-expresses every recipe rule as one fallback rule per
// distinct variant chain, in recipe order. Utilities that share a chain share a
// rule, so `@apply focus-visible:border-ring focus-visible:ring-[3px]` becomes
// a single `:focus-visible` rule with both utilities — the shape the file has
// always had.
func siteButtonRules(shape recipe.Shape, style recipe.Style) ([]siteButtonRule, error) {
	return buttonFallbackRules(shape, style, siteButtonSelector)
}

// buttonFallbackRules is the recipe→fallback-rule translation shared by every
// Button fallback stylesheet. The composer decides only what a rule's selector
// looks like — web/site-button.css scopes to the site body, the theme-preview
// fallback scopes into one preview section — while the grouping of utilities by
// variant chain, in recipe order, is identical for all of them.
func buttonFallbackRules(
	shape recipe.Shape,
	style recipe.Style,
	compose func(dimensionAttr string, variants []string) (string, error),
) ([]siteButtonRule, error) {
	if shape.Component != siteButtonComponent {
		return nil, fmt.Errorf("site fallback is Button's, but shape declares component %q", shape.Component)
	}
	var out []siteButtonRule
	for _, rule := range style.Rules() {
		slot, dimension, value, kind, err := shape.DecodeClass(rule.Class)
		if err != nil {
			return nil, fmt.Errorf("decode %s recipe class %s: %w", siteButtonComponent, rule.Class, err)
		}
		if slot != "" {
			// Button is a single-slot component. A second slot would need its own
			// marker in the fallback, and guessing one would be wrong.
			return nil, fmt.Errorf(
				"site fallback cannot render %s slot %q: the fallback targets only the root marker",
				siteButtonComponent, slot)
		}
		var dimensionAttr string
		if kind != recipe.ClassBase {
			dimensionAttr = fmt.Sprintf("[data-%s=%q]", dimension, value)
		}
		// Utilities are grouped by variant chain, in first-appearance order, so
		// the emitted rules follow the recipe's own reading order. The chain is
		// carried alongside its joined form rather than re-split from it: a
		// variant like `[&_svg:not([class*='size-'])]` contains colons of its own.
		type group struct {
			variants  []string
			utilities []string
		}
		var order []string
		grouped := map[string]*group{}
		for _, utility := range rule.Utilities {
			variants, base, err := splitUtilityVariants(utility)
			if err != nil {
				return nil, fmt.Errorf("%s recipe class %s: %w", siteButtonComponent, rule.Class, err)
			}
			chain := strings.Join(variants, ":")
			if grouped[chain] == nil {
				order = append(order, chain)
				grouped[chain] = &group{variants: variants}
			}
			grouped[chain].utilities = append(grouped[chain].utilities, base)
		}
		for _, chain := range order {
			selector, err := compose(dimensionAttr, grouped[chain].variants)
			if err != nil {
				return nil, fmt.Errorf("%s recipe class %s: %w", siteButtonComponent, rule.Class, err)
			}
			out = append(out, siteButtonRule{selector: selector, utilities: grouped[chain].utilities})
		}
	}
	return out, nil
}

// siteButtonSelector composes one fallback selector.
//
// The two arms differ in where the attribute compounds land, and that is not
// cosmetic. In the light arm they sit OUTSIDE the :where(), giving the rule
// specificity (0,1,0) so it can beat foundation defaults; in the `.dark` arm the
// `.dark` ancestor already supplies (0,1,0), so the attributes stay inside the
// :where() and the arm keeps the same weight as its light counterpart rather
// than outranking it.
func siteButtonSelector(dimensionAttr string, variants []string) (string, error) {
	marker := slotMarker(siteButtonComponent, "")
	parts, err := buttonVariantParts(dimensionAttr, variants)
	if err != nil {
		return "", err
	}
	if parts.dark {
		return ".dark " + siteButtonScope + " :where([" + marker + "]" + parts.attrs + ")" + parts.pseudos + parts.descendant, nil
	}
	return siteButtonScope + " :where([" + marker + "])" + parts.attrs + parts.pseudos + parts.descendant, nil
}

// buttonVariantParts is the shared decomposition behind every fallback selector
// composer: it folds a variant chain through the closed siteButtonVariants
// table into the attribute compounds, pseudo-class suffix, descendant compound
// and dark-arm flag the composer arranges into its own selector shape.
func buttonVariantParts(dimensionAttr string, variants []string) (buttonSelectorParts, error) {
	parts := buttonSelectorParts{attrs: dimensionAttr}
	for _, name := range variants {
		form, ok := siteButtonVariants[name]
		if !ok {
			return parts, fmt.Errorf(
				"variant %q has no site-fallback selector form; add it to siteButtonVariants", name)
		}
		switch {
		case form.dark:
			parts.dark = true
		case form.attr != "":
			parts.attrs += form.attr
		case form.pseudo != "":
			parts.pseudos += form.pseudo
		case form.descendant != "":
			if parts.descendant != "" {
				return parts, fmt.Errorf("variant chain selects two descendants: %q and %q", parts.descendant, form.descendant)
			}
			parts.descendant = form.descendant
		}
	}
	return parts, nil
}

// buttonSelectorParts is one variant chain decomposed into selector fragments.
type buttonSelectorParts struct {
	attrs      string
	pseudos    string
	descendant string
	dark       bool
}

// splitUtilityVariants splits a Tailwind utility into its variant chain and the
// bare utility. Colons inside brackets belong to the variant or the value, not
// to the chain, so the split tracks bracket depth.
func splitUtilityVariants(utility string) ([]string, string, error) {
	var parts []string
	depth, start := 0, 0
	for i := 0; i < len(utility); i++ {
		switch utility[i] {
		case '[':
			depth++
		case ']':
			depth--
			if depth < 0 {
				return nil, "", fmt.Errorf("utility %q closes a bracket that was never opened", utility)
			}
		case ':':
			if depth == 0 {
				parts = append(parts, utility[start:i])
				start = i + 1
			}
		}
	}
	if depth != 0 {
		return nil, "", fmt.Errorf("utility %q leaves a bracket unclosed", utility)
	}
	base := utility[start:]
	if base == "" {
		return nil, "", fmt.Errorf("utility %q has an empty base", utility)
	}
	return parts, base, nil
}

// loadSiteButtonRules parses the default style's Button recipe and returns the
// fallback rules it generates, for callers that have no parsed recipe in hand.
func loadSiteButtonRules(root string) ([]siteButtonRule, error) {
	shape, ok := shapes.All()[siteButtonComponent]
	if !ok {
		return nil, fmt.Errorf("component %s declares no shape", siteButtonComponent)
	}
	path := filepath.Join(root, "registry", "styles", DefaultStyle, siteButtonComponent+".css")
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read %s %s recipe: %w", DefaultStyle, siteButtonComponent, err)
	}
	parsed, err := recipe.ParseStyle(path, src)
	if err != nil {
		return nil, fmt.Errorf("parse %s %s recipe: %w", DefaultStyle, siteButtonComponent, err)
	}
	generated, rules, err := siteButtonStylesheet(shape, parsed)
	if err != nil {
		return nil, err
	}
	// The exemptions below describe the file the generator produces. If the
	// committed file has drifted from it, they describe something that is not on
	// disk, so the derivation is not sound and the gate must say so rather than
	// forgive rules it did not derive.
	onDisk, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(siteButtonPath)))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", siteButtonPath, err)
	}
	if string(onDisk) != string(generated) {
		return nil, fmt.Errorf(
			"%s has drifted from Button's %s recipe; run go run ./cmd/stylegen",
			siteButtonPath, DefaultStyle)
	}
	return rules, nil
}

// siteButtonFallbackReason is the single decision behind every derived
// exemption. It is attached to each one because a reader who trips over a
// suppressed rule should learn why it is suppressed from the diagnostic, not
// from a comment somewhere else in the tree.
const siteButtonFallbackReason = "web/site-button.css is GENERATED from Button's " + DefaultStyle + " recipe by cmd/stylegen: " +
	"it is docs-and-demos-only presentation for raw markup that carries [data-gsxui-slot-button] " +
	"WITHOUT rendering through <ui.Button> — hand-written examples and the theme preview. Restating " +
	"Button's own utilities is the file's entire purpose, so every declaration in it necessarily " +
	"contests Button; it is authored at zero specificity in @layer components precisely so the " +
	"compiled Button's own utilities beat it wherever a real Button is rendered. Losing the cascade " +
	"there is the design, not a defect. jstest/specs/basic-demo-presentation.spec.ts:182 pins that " +
	"both halves still hold in the browser."

// siteButtonFallbackExemptions derives, rather than restates, every violation
// the generated fallback commits.
//
// The list this replaced was 56 hand-written (selector, utility) pairs — 112
// entries once expanded per style — that had to be re-copied by hand every time
// Button's recipe changed. It could not be reduced to the single string
// "web/site-button.css": keying by file alone forgives every rule anyone adds to
// that file afterwards, and that is exactly the blind spot the enumeration
// exists to close.
//
// Generation dissolves that trade-off. The pairs come from the SAME rules the
// generator emits, so the set is exact by construction and nobody maintains it,
// while the thing a file-level waiver would have hidden — a hand-added rule —
// cannot exist: loadSiteButtonRules fails unless the committed file is byte-for-
// byte the generator's output, so the only way to add a rule here is to change
// Button's recipe, which is precisely what the exemption says this file
// restates.
//
// EVERY STYLE IS EXEMPT, and unlike the hand-written list that is derived rather
// than declared. The old list named its styles because each pair's contest was a
// per-style FACT about values — `rounded-lg` is contested under Nova and
// `rounded-4xl` under Maia. Here the claim is structural and holds for any style
// whatsoever: these rules restate the default style's Button against the marker,
// and Button's own compiled utilities — whichever style compiled them — are
// meant to win. A new style inherits that by construction, not by oversight.
//
// Staleness is checked per GROUP rather than per entry (see staleExemptions).
// A derived entry that stops matching is not a decision that lost its subject —
// it is a recipe utility that happens to restate a value nothing else contests,
// which is not a fact anyone decided or should have to re-decide.
func siteButtonFallbackExemptions(root string) ([]layerCheckExemption, error) {
	rules, err := loadSiteButtonRules(root)
	if err != nil {
		return nil, err
	}
	styles, err := styleNames(root)
	if err != nil {
		return nil, err
	}
	var out []layerCheckExemption
	for _, style := range styles {
		for _, rule := range rules {
			selector := normalizeSelectorKey(rule.selector)
			for _, utility := range rule.utilities {
				out = append(out, layerCheckExemption{
					key: exemptionKey{
						file:      siteButtonPath,
						style:     style,
						selector:  selector,
						contested: utility,
					},
					reason:  siteButtonFallbackReason,
					derived: siteButtonDerivedGroup,
				})
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].key.style != out[j].key.style {
			return out[i].key.style < out[j].key.style
		}
		if out[i].key.selector != out[j].key.selector {
			return out[i].key.selector < out[j].key.selector
		}
		return out[i].key.contested < out[j].key.contested
	})
	return out, nil
}
