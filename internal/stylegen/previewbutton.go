// previewButtonPath is the theme-preview Button fallback stylesheet,
// slash-separated and relative to the repository root. Like web/site-button.css
// it is a GENERATED artifact, but where the site fallback restates only the
// default style's Button recipe, this one restates EVERY style's recipe, each
// scoped inside its own preview section.
//
// The preview body stamps data-theme-button-preview, which scope-disables the
// site fallback — correctly, because the maia section must never receive
// Nova's chrome. But raw slot-button markup inside the gallery (Calendar's day
// and nav buttons, Pagination links) depends on a fallback for its Button
// chrome. This file is that fallback: the nova section gets Nova's Button
// recipe, the maia section gets Maia's.
const previewButtonPath = "web/theme-preview-button.css"

// previewButtonHeader is the generated file's provenance comment.
const previewButtonHeader = `/* Code generated by cmd/stylegen from registry/styles/<style>/button.css for every authored style. DO NOT EDIT.

   Theme-preview Button fallback for raw markup that carries
   [data-gsxui-slot-button] without rendering through <ui.Button> — Calendar's
   day and nav buttons, Pagination links. The preview body scope-disables
   web/site-button.css (the maia section must not receive Nova's chrome), so
   each style's Button recipe is restated here inside its own
   [data-theme-preview-style] section instead.

   Every rule is one of that style's Button recipe rules re-expressed against
   the slot marker, in @layer components so a real Button's own compiled
   utilities always beat it. */
`

// previewButtonSelector composes one fallback selector for one style's section.
//
// The section attribute is the scope AND the specificity source: it supplies
// (0,1,0) the way `.dark` does in web/site-button.css's dark arm, so the marker
// and nothing else stays inside the :where() while dimension and variant
// attributes land outside it — a dimension rule then outranks its base rule
// structurally instead of by emission order. The dark arm wraps `.dark` in
// :where() so both arms keep the same weight and the dark values win by recipe
// order, exactly the parity web/site-button.css preserves.
func previewButtonSelector(styleName string) func(dimensionAttr string, variants []string) (string, error) {
	scope := fmt.Sprintf("[data-theme-preview-style=%q]", styleName)
	marker := slotMarker(siteButtonComponent, "")
	return func(dimensionAttr string, variants []string) (string, error) {
		parts, err := buttonVariantParts(dimensionAttr, variants)
		if err != nil {
			return "", err
		}
		selector := scope + " :where([" + marker + "])" + parts.attrs + parts.pseudos + parts.descendant
		if parts.dark {
			selector = ":where(.dark) " + selector
		}
		return selector, nil
	}
}

// previewButtonStylesheet renders every style's Button recipe as the preview
// fallback, one scoped block per style in the given order. It returns the file
// bytes and the structured rules per style, because the layer gate derives its
// exemptions from the same rules rather than from a hand-copied list.
func previewButtonStylesheet(
	shape recipe.Shape,
	styles []string,
	parsed map[string]recipe.Style,
) ([]byte, map[string][]siteButtonRule, error) {
	rulesByStyle := make(map[string][]siteButtonRule, len(styles))
	var b strings.Builder
	b.WriteString(previewButtonHeader)
	b.WriteString("@layer components {\n")
	for _, style := range styles {
		recipeStyle, ok := parsed[style]
		if !ok {
			return nil, nil, fmt.Errorf("preview fallback: style %q has no parsed Button recipe", style)
		}
		rules, err := buttonFallbackRules(shape, recipeStyle, previewButtonSelector(style))
		if err != nil {
			return nil, nil, fmt.Errorf("preview fallback for style %s: %w", style, err)
		}
		rulesByStyle[style] = rules
		fmt.Fprintf(&b, "  /* %s section: registry/styles/%s/button.css */\n", style, style)
		for _, rule := range rules {
			fmt.Fprintf(&b, "  %s {\n    @apply %s;\n  }\n", rule.selector, strings.Join(rule.utilities, " "))
		}
	}
	b.WriteString("}\n")
	return []byte(b.String()), rulesByStyle, nil
}

// loadPreviewButtonRules parses every style's Button recipe and returns the
// fallback rules the preview stylesheet generates from them, for callers that
// have no parsed recipes in hand. Like loadSiteButtonRules, it fails when the
// committed file has drifted from the generator's output, because exemptions
// derived from rules that are not on disk describe nothing.
func loadPreviewButtonRules(root string) (map[string][]siteButtonRule, error) {
	shape, ok := shapes.All()[siteButtonComponent]
	if !ok {
		return nil, fmt.Errorf("component %s declares no shape", siteButtonComponent)
	}
	styles, err := styleNames(root)
	if err != nil {
		return nil, err
	}
	parsed := make(map[string]recipe.Style, len(styles))
	for _, style := range styles {
		path := filepath.Join(root, "registry", "styles", style, siteButtonComponent+".css")
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s %s recipe: %w", style, siteButtonComponent, err)
		}
		parsedStyle, err := recipe.ParseStyle(path, src)
		if err != nil {
			return nil, fmt.Errorf("parse %s %s recipe: %w", style, siteButtonComponent, err)
		}
		parsed[style] = parsedStyle
	}
	generated, rules, err := previewButtonStylesheet(shape, styles, parsed)
	if err != nil {
		return nil, err
	}
	onDisk, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(previewButtonPath)))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", previewButtonPath, err)
	}
	if string(onDisk) != string(generated) {
		return nil, fmt.Errorf(
			"%s has drifted from the styles' Button recipes; run go run ./cmd/stylegen",
			previewButtonPath)
	}
	return rules, nil
}

// previewButtonDerivedGroup names the preview fallback's derived exemption
// group, mirroring siteButtonDerivedGroup.
const previewButtonDerivedGroup = "web/theme-preview-button.css (generated from every style's Button recipe)"

// previewButtonFallbackReason is the single decision behind every derived
// exemption for the preview fallback.
const previewButtonFallbackReason = "web/theme-preview-button.css is GENERATED from every style's Button recipe by " +
	"cmd/stylegen: it is theme-preview-only presentation for raw markup that carries " +
	"[data-gsxui-slot-button] WITHOUT rendering through <ui.Button> — Calendar day/nav buttons and " +
	"Pagination links inside the gallery. The preview body scope-disables web/site-button.css so the " +
	"maia section never receives Nova's chrome; this file restates each style's Button utilities " +
	"inside that style's own [data-theme-preview-style] section instead. Restating Button's own " +
	"utilities is the file's entire purpose, so every declaration in it necessarily contests Button; " +
	"it lives in @layer components precisely so a real Button's compiled utilities beat it wherever a " +
	"real Button renders. Losing the cascade there is the design, not a defect."

// previewButtonFallbackExemptions derives every violation the generated preview
// fallback commits, exactly the way siteButtonFallbackExemptions does for the
// site fallback. Every gate style is exempt for every emitted rule: the claim
// is structural — these rules restate a style's Button against the marker
// inside that style's own preview section, and Button's compiled utilities are
// meant to win — and holds for any style whatsoever.
func previewButtonFallbackExemptions(root string) ([]layerCheckExemption, error) {
	rulesByStyle, err := loadPreviewButtonRules(root)
	if err != nil {
		return nil, err
	}
	styles, err := styleNames(root)
	if err != nil {
		return nil, err
	}
	var out []layerCheckExemption
	for _, gateStyle := range styles {
		for _, sourceStyle := range styles {
			for _, rule := range rulesByStyle[sourceStyle] {
				selector := normalizeSelectorKey(rule.selector)
				for _, utility := range rule.utilities {
					out = append(out, layerCheckExemption{
						key: exemptionKey{
							file:      previewButtonPath,
							style:     gateStyle,
							selector:  selector,
							contested: utility,
						},
						reason:  previewButtonFallbackReason,
						derived: previewButtonDerivedGroup,
					})
				}
			}
		}
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].key.style != out[j].key.style {
			return out[i].key.style < out[j].key.style
		}
		if out[i].key.selector != out[j].key.selector {
			return out[i].key.selector < out[j].key.selector
		}
		return out[i].key.contested < out[j].key.contested
	})
	return out, nil
}
